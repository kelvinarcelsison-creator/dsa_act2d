    private void btn_addActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_addActionPerformed
        // TODO add your handling code here:
        String id = txt_id.getText().trim();
        String name = txt_name.getText().trim();
        String course = txt_course.getText().trim();
        String email = txt_email.getText().trim();

        if (id.isEmpty() || name.isEmpty() ||
            course.isEmpty() || email.isEmpty()) {

            JOptionPane.showMessageDialog(
                this,
                "Please fill in all fields."
            );
            return;
        }

        try {

            pst = conn.prepareStatement(
                "INSERT INTO students " +
                "(student_id, name, course, email) " +
                "VALUES (?, ?, ?, ?)"
            );

            pst.setString(1, id);
            pst.setString(2, name);
            pst.setString(3, course);
            pst.setString(4, email);

            pst.executeUpdate();

            loadTable();
            clearFields();

            JOptionPane.showMessageDialog(
                this,
                "Student added successfully."
            );

        } catch (SQLException ex) {

            JOptionPane.showMessageDialog(
                this,
                "Add error: " + ex.getMessage()
            );
        }

    }//GEN-LAST:event_btn_addActionPerformed

    private void btn_updateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_updateActionPerformed
        // TODO add your handling code here:

        int row = jTable1.getSelectedRow();

        if (row < 0) {
            JOptionPane.showMessageDialog(
                this,
                "Select a student in the table first."
            );
            return;
        }

        // Get the OLD student_id from column 1
        String oldId = jTable1.getValueAt(row, 1).toString();

        String id = txt_id.getText().trim();
        String name = txt_name.getText().trim();
        String course = txt_course.getText().trim();
        String email = txt_email.getText().trim();

        if (id.isEmpty() || name.isEmpty() ||
            course.isEmpty() || email.isEmpty()) {

            JOptionPane.showMessageDialog(
                this,
                "Please fill in all fields."
            );
            return;
        }

        try {
            pst = conn.prepareStatement(
                "UPDATE students " +
                "SET student_id=?, name=?, course=?, email=? " +
                "WHERE student_id=?"
            );

            pst.setString(1, id);
            pst.setString(2, name);
            pst.setString(3, course);
            pst.setString(4, email);
            pst.setString(5, oldId);

            pst.executeUpdate();

            loadTable();
            clearFields();

            JOptionPane.showMessageDialog(
                this,
                "Student updated successfully."
            );

        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(
                this,
                "Update error: " + ex.getMessage()
            );
        }
    }//GEN-LAST:event_btn_updateActionPerformed

    private void btn_deleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_deleteActionPerformed
        // TODO add your handling code here:

        int row = jTable1.getSelectedRow();

        if (row < 0) {
            JOptionPane.showMessageDialog(
                this,
                "Select a student in the table first."
            );
            return;
        }

        int choice = JOptionPane.showConfirmDialog(
            this,
            "Delete the selected student?",
            "Confirm Delete",
            JOptionPane.YES_NO_OPTION
        );

        if (choice == JOptionPane.YES_OPTION) {

            try {
                String studentId =
                jTable1.getValueAt(row, 1).toString();

                pst = conn.prepareStatement(
                    "DELETE FROM students WHERE student_id=?"
                );

                pst.setString(1, studentId);
                pst.executeUpdate();

                loadTable();
                clearFields();

                JOptionPane.showMessageDialog(
                    this,
                    "Student deleted successfully."
                );

            } catch (SQLException ex) {
                JOptionPane.showMessageDialog(
                    this,
                    "Delete error: " + ex.getMessage()
                );
            }
        }
    }//GEN-LAST:event_btn_deleteActionPerformed

